"""Port of agentic-rag-mastra src/lib/grading.ts. Pure and deterministic.

Parity with the TypeScript original is pinned by tests/fixtures/grading_parity.json,
generated by scripts/grading_fixture.ts from the original module.
"""

import re

REFUSAL_MARKER = "[KEINE_GRUNDLAGE]"
_CITATION = re.compile(r"\[chunk:([a-z0-9-]+)\]")
_THINK = re.compile(r"<think>.*?</think>", re.DOTALL)


def strip_think(answer: str) -> str:
    """Drop Qwen3 <think> blocks (empty ones appear even with thinking disabled)."""
    return _THINK.sub("", answer).strip()


def has_thinking(answer: str) -> bool:
    """True when a <think> block holds any non-whitespace text."""
    return any(m.strip() for m in re.findall(r"<think>(.*?)</think>", answer, re.DOTALL))


def parse_citations(answer: str) -> list[str]:
    return list(dict.fromkeys(_CITATION.findall(answer)))


def is_refusal(answer: str) -> bool:
    return REFUSAL_MARKER in answer


def citation_validity(answer: str, retrieved_ids: set[str]) -> int:
    cited = parse_citations(answer)
    if not cited:
        return 1 if is_refusal(answer) else 0
    return 1 if all(c in retrieved_ids for c in cited) else 0


def refusal_correctness(expected: str, answer: str) -> int:
    return 1 if (expected == "refused") == is_refusal(answer) else 0


def citation_recall(expected_chunks: list[str], answer: str) -> float | None:
    if not expected_chunks or is_refusal(answer):
        return None
    cited = set(parse_citations(answer))
    return sum(1 for c in expected_chunks if c in cited) / len(expected_chunks)


def normalize(text: str) -> str:
    # JS `\d` and `\b` are ASCII-only even with the u flag; mirror that explicitly.
    text = text.lower()
    text = re.sub(r"(?<=[0-9])[.\s](?=[0-9]{3}(?![0-9A-Za-z_]))", "", text)
    return re.sub(r"\s+", " ", text)


def fact_coverage(facts: list[str] | None, answer: str) -> float | None:
    if not facts or is_refusal(answer):
        return None
    text = normalize(answer)
    hits = [f for f in facts if any(normalize(a.strip()) in text for a in f.split("|"))]
    return len(hits) / len(facts)
